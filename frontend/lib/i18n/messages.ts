export const messages = { "zh-CN": zh, en } as const;
export type { TranslationKey };

export function normalizeLocale(value?: string | null): Locale {
  return value?.toLowerCase().startsWith("en") ? "en" : DEFAULT_LOCALE;
}

export function createTranslator(locale: Locale) {
  return (key: TranslationKey, values?: Record<string, string | number>) => {
    let text: string = messages[locale][key] ?? messages[DEFAULT_LOCALE][key];
    if (values) {
      for (const [name, value] of Object.entries(values)) {
        text = text.replaceAll(`{${name}}`, String(value));
      }
    }
    return text;
  };
}

export function getClientLocale(): Locale {
  if (typeof document === "undefined") return DEFAULT_LOCALE;
  const match = document.cookie.match(
    new RegExp(`(?:^|; )${LOCALE_COOKIE}=([^;]*)`),
  );
  return normalizeLocale(match?.[1] ? decodeURIComponent(match[1]) : null);
}

export function getClientTranslator() {
  return createTranslator(getClientLocale());
}
